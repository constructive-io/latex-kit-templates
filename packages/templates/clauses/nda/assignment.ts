import { defineClause } from 'latex-kit';

export default defineClause({
  title: 'Assignment',
  version: 1,
  body: `Neither party may assign this Agreement without the other party's
written consent, except to a successor of its whole business. \\when{mutual}{It
binds and benefits both parties' successors.}\\otherwise{It binds the
Recipient's successors.}`,
});
